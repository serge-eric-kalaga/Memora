"""Le contrôle CI doit détecter un champ ajouté sans migration correspondante."""

import pytest
import sqlalchemy as sa
from alembic.util.exc import AutogenerateDiffsDetected

from api.database import Base
from scripts.check_migrations import check_migrations


def test_ci_rejects_model_change_without_migration():
    """Une base créée avec les métadonnées courantes masquerait cette régression."""
    table = Base.metadata.tables["user"]
    column = sa.Column("ci_unmigrated_probe", sa.String(80), nullable=True)
    table.append_column(column)
    try:
        with pytest.raises(AutogenerateDiffsDetected):
            check_migrations()
    finally:
        table._columns.remove(column)


def test_ci_accepts_current_migrations_without_downgrading_security_boundary(
    monkeypatch, capsys
):
    from alembic.config import Config
    from alembic.script import ScriptDirectory
    from pathlib import Path

    monkeypatch.delenv("TEST_MIGRATION_DATABASE_URL", raising=False)
    root = Path(__file__).resolve().parents[1]
    scripts = ScriptDirectory.from_config(Config(str(root / "alembic.ini")))
    head = scripts.get_revision(scripts.get_current_head())
    result = check_migrations()
    assert result["head"] == head.revision
    expected_roundtrip = (
        head.down_revision
        if getattr(head.module, "irreversible_security", False)
        else head.revision
    )
    assert result["roundtrip"] == expected_roundtrip
    assert "données conservées" in capsys.readouterr().out
